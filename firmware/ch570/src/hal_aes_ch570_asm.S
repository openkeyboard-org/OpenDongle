/* ==========================================================================
 * VARIANT A — rolled row-major SWAR, S-box in SRAM, called S-box helper.
 * 1,669 cycles/block. In a real link of this firmware it adds 840 B of SRAM:
 * 404 B .highcode + 256 B S-box + 176 B schedule = 836 B nominal, plus 4 B of
 * .data alignment padding. (A bench build reports 400 B of code rather than
 * 404 -- different alignment and relaxation. Trust the firmware link.)
 * Zero spills: 16 registers, all caller-saved, no stack frame at all.
 * Build with -Wa,--defsym,AES_A_INLINE=1 to inline the S-box helper instead:
 * 1,509 cycles for +100 B, which spends the margin this variant exists for.
 * ========================================================================== */

/*
 * OpenDongle -- AES-128 forward cipher, variant A: compact ROLLED assembly.
 * CH570 / QingKe V3C, rv32imc_zba_zbb_zbc_zbs_xw, ilp32.
 *
 * The budget-safe candidate.  956 B of SRAM are available in total, the S-box
 * takes 256 and the round-key schedule 176, so everything else here has to live
 * in what is left -- and the point of this variant is to leave slack, not to
 * spend the last byte.
 *
 * COST MODEL THIS WAS WRITTEN AGAINST (measured on CH570, SRAM-resident):
 *
 *   ALU / shift / rori / mul / clmul / Zbb / Zbs   1 cycle, fully forwarded
 *   lw / lbu / sw / sb                             2 cycles
 *   taken branch or jump                           2 cycles
 *   not-taken branch                               1 cycle
 *
 * There is NO load-use interlock on this core: a load followed immediately by
 * its dependent consumer costs exactly the same as a load followed by an
 * independent instruction.  So nothing below wastes an instruction or a
 * register scheduling around the S-box loads -- every `lbu` is followed
 * directly by the instruction that consumes it.  A byte load also costs the
 * same as a word load, so `xw`'s 2-byte `c.lbu` is a pure code-size win at
 * identical speed, which is what makes this variant's size possible at all.
 *
 * SHAPE
 *
 *   State is four 32-bit words, one per ROW of the AES state, held in a0..a3
 *   for the entire cipher.  r[row] byte j is in[4j + row].  In that layout:
 *
 *     - ShiftRows is one `rori` per row, applied to the INPUT of the S-box pass
 *       rather than its output (the S-box is byte-wise, so the two commute);
 *     - MixColumns is a SWAR xtime over whole words -- four GF(2^8) doublings
 *       per instruction group, no table at all;
 *     - AddRoundKey is four word loads from a schedule pre-transposed into the
 *       same row layout by hal_aes_set_key().
 *
 * ROLLED, NOT UNROLLED
 *
 *   Unrolling won 15% for the C cipher when it ran from FLASH, because every
 *   taken back-edge restarted this core's prefetcher.  From SRAM a taken branch
 *   costs 2 cycles and a not-taken one 1, so the entire loop control of this
 *   kernel is worth almost nothing.  MEASURED, like for like (both builds
 *   inlining the S-box pass, so the loop is the only difference):
 *
 *     rolled    504 B   1558 cycles
 *     unrolled 3232 B   1502 cycles     -56 cycles (-3.6%) for +2728 B
 *
 *   Forty-nine bytes per cycle, and 3.8x over the SRAM budget.  AES_A_UNROLL=1
 *   builds it so the claim is measured rather than asserted.
 *
 * REGISTER ALLOCATION -- 16 registers, zero spills, no stack frame at all
 *
 *   a0 a1 a2 a3  state rows r0..r3          (x10..x13: the compressed set, so
 *                                            every state XOR is a 2-byte c.xor
 *                                            and every output store a 2-byte
 *                                            xw c.sb)
 *   a4           sub4 result / general temp / MixColumns w2
 *   a5           sub4 address temp; input pointer in the prologue, output
 *                pointer in the epilogue
 *   a6           output pointer, held across the cipher
 *   a7           MixColumns t = r0^r1^r2^r3
 *   t0           S-box base                 (SRAM)
 *   t1           round-key pointer          (SRAM, walks the schedule)
 *   t2           round counter
 *   t3           0x80808080                 (SWAR xtime carry mask)
 *   t4           0x1b                       (SWAR xtime reduction polynomial)
 *   t5           saved return address       (ra is the link for sub4)
 *   t6           sub4 argument / MixColumns w0
 *   ra           link register / MixColumns w1 (nothing is called from inside
 *                MixColumns, so ra is a free temp there)
 *
 *   Nothing callee-saved is touched, so there is no prologue, no epilogue and
 *   no stack traffic: not one sw/lw relative to sp anywhere in this file.
 *   Grep the listing for "(sp)" -- there are zero hits.
 *
 * BUILD SWITCHES (assembler --defsym, all optional)
 *
 *   AES_A_INLINE=1   inline the four S-box passes instead of calling sub4:
 *                    1798 -> 1558 cycles/block (-13%) for +100 B.  Still fits
 *                    (936 B of 956) but leaves only 20 B of margin against this
 *                    build's 120; offered, not shipped.  See README.md.
 *   AES_A_UNROLL=1   fully unroll the ten rounds (implies inlining).  Does NOT
 *                    fit; built only to measure what unrolling is worth here.
 */

/*
 * Deliberately NO `.align 2` here.  RISC-V with the C extension has IALIGN=16,
 * so a 2-byte-aligned entry is architecturally fine, and asking for 4 makes GAS
 * pad the section tail with a c.nop and the linker round up again -- four bytes
 * for nothing.  Alignment padding was separately measured on this core (Exp C
 * in OPTIMISATION-LOG.md: -falign-functions/loops=32 was both slower and
 * bigger), so there is no fetch reason to buy it back.
 */
	.section .highcode.aes_a, "ax", @progbits

.ifdef AES_A_UNROLL
	AES_A_INLINE = 1
.endif

/* --------------------------------------------------------------- macros -- */

/*
 * One state row of the input transpose:  r = in[k] | in[k+4]<<8 | ...
 * lbu compresses to the 2-byte xw c.lbu (5-bit offset, base and destination in
 * x8..x15), which is why a5 holds the input pointer and a4 the byte.
 */
.macro ROWIN reg, k
	lbu	\reg, \k+0(a5)
	lbu	a4, \k+4(a5)
	slli	a4, a4, 8
	or	\reg, \reg, a4
	lbu	a4, \k+8(a5)
	slli	a4, a4, 16
	or	\reg, \reg, a4
	lbu	a4, \k+12(a5)
	slli	a4, a4, 24
	or	\reg, \reg, a4
.endm

/* One state row of the output transpose.  Destroys \reg; sb -> xw c.sb. */
.macro ROWOUT reg, k
	sb	\reg, \k+0(a5)
	srli	\reg, \reg, 8
	sb	\reg, \k+4(a5)
	srli	\reg, \reg, 8
	sb	\reg, \k+8(a5)
	srli	\reg, \reg, 8
	sb	\reg, \k+12(a5)
.endm

/*
 * Four GF(2^8) doublings at once, in place on a4, temp a5.
 *
 *   m  = x & 0x80808080          the bits that would overflow their byte
 *   y  = (x ^ m) << 1            i.e. (x & 0x7f7f7f7f) << 1 -- reusing m costs
 *                                nothing and avoids a second mask constant
 *   m  = (m >> 7) * 0x1b         0x1b into every byte whose msb was set; the
 *                                multiplicand has isolated bits at 8k so the
 *                                integer multiply cannot carry between bytes
 *   x' = y ^ m
 *
 * Six instructions, 16 bytes, six cycles (mul is single-cycle here), two
 * constant registers.  The `andn` form is the same instruction count and two
 * bytes longer.  clmul was considered and rejected: multiply-by-2 IS a shift,
 * and clmul cannot isolate the per-byte msb, so it saves nothing.
 */
.macro XT4
	and	a5, a4, t3
	xor	a4, a4, a5
	slli	a4, a4, 1
	srli	a5, a5, 7
	mul	a5, a5, t4
	xor	a4, a4, a5
.endm

/*
 * Non-destructive extraction of byte \b of \src into a5.
 *   b=0  andi                       4 B, 1 instr
 *   b=1  slli 16 ; srli 24          6 B, 2 instr
 *   b=2  slli  8 ; srli 24          6 B, 2 instr
 *   b=3  srli 24                    4 B, 1 instr
 * The shift pair beats srli+andi because `andi rd,rs,255` is four bytes and
 * cannot compress, while the second half of a shift pair can.
 */
.macro GETB src, b
.if \b == 0
	andi	a5, \src, 255
.elseif \b == 1
	slli	a5, \src, 16
	srli	a5, a5, 24
.elseif \b == 2
	slli	a5, \src, 8
	srli	a5, a5, 24
.else
	srli	a5, \src, 24
.endif
.endm

/* Destructive extraction of byte \b of \reg into \reg -- two bytes cheaper
 * because the two-operand compressed shift forms apply. */
.macro GETBD reg, b
.if \b == 0
	andi	\reg, \reg, 255
.elseif \b == 1
	slli	\reg, \reg, 16
	srli	\reg, \reg, 24
.elseif \b == 2
	slli	\reg, \reg, 8
	srli	\reg, \reg, 24
.else
	srli	\reg, \reg, 24
.endif
.endm

/*
 * Inlined SubBytes+ShiftRows for row \r, in place on \reg.
 *
 * The ShiftRows rotate is folded in by permuting which source byte feeds which
 * output byte -- output byte j takes source byte (j + r) mod 4 -- so the `rori`
 * disappears entirely.  Every source byte is still extracted exactly once, so
 * the fold is free; only the ORDER changes.
 *
 * (aes_sw.c records this same transformation measuring 37% SLOWER in C.  That
 * was a compiler effect: four rotate-folded expansions of sub4 stopped GCC
 * sharing work between them.  Here the four expansions are written out anyway
 * and the register allocation is fixed by hand, so there is nothing left to
 * lose -- the fold is a strict removal of three instructions per round.)
 */
.macro SUBROW_INLINE reg, r
	GETB	\reg, ((\r + 0) % 4)
	add	a5, a5, t0
	lbu	a4, 0(a5)
	GETB	\reg, ((\r + 1) % 4)
	add	a5, a5, t0
	lbu	a5, 0(a5)
	slli	a5, a5, 8
	or	a4, a4, a5
	GETB	\reg, ((\r + 2) % 4)
	add	a5, a5, t0
	lbu	a5, 0(a5)
	slli	a5, a5, 16
	or	a4, a4, a5
	GETBD	\reg, ((\r + 3) % 4)
	add	\reg, \reg, t0
	lbu	\reg, 0(\reg)
	slli	\reg, \reg, 24
	or	\reg, \reg, a4
.endm

/*
 * Called SubBytes+ShiftRows for row \r.  The rotate writes straight into the
 * argument register, so rows 1..3 pay no separate `mv` -- the rori IS the
 * argument move.
 */
.macro SUBROW_CALL reg, r
.if \r == 0
	mv	t6, \reg
.else
	rori	t6, \reg, 8*\r
.endif
	jal	ra, aes_a_sub4
	mv	\reg, a4
.endm

.macro SUBROW reg, r
.ifdef AES_A_INLINE
	SUBROW_INLINE	\reg, \r
.else
	SUBROW_CALL	\reg, \r
.endif
.endm

/*
 * MixColumns.
 *
 *   n_i = r_i ^ t ^ xtime(r_i ^ r_{i+1}),   t = r0^r1^r2^r3
 *
 * Fold t into each combiner, w_i = t ^ xtime(r_i ^ r_{i+1}).  Then
 *
 *   w0 ^ w1 ^ w2 = t ^ xtime(r0^r3) = w3
 *
 * because xtime is F2-linear and t^t^t = t.  That derives the fourth combiner
 * in two XORs instead of a whole six-instruction xtime: four instructions saved
 * per round, 36 per block, for no extra register.
 */
.macro MIXCOLUMNS
	xor	a7, a0, a1
	xor	a7, a7, a2
	xor	a7, a7, a3		/* t                                 */
	xor	a4, a0, a1
	XT4
	xor	t6, a4, a7		/* w0                                */
	xor	a4, a1, a2
	XT4
	xor	ra, a4, a7		/* w1                                */
	xor	a4, a2, a3
	XT4
	xor	a4, a4, a7		/* w2                                */
	xor	a0, a0, t6
	xor	a1, a1, ra
	xor	a2, a2, a4
	xor	a4, a4, t6
	xor	a4, a4, ra		/* w3 = w0 ^ w1 ^ w2                 */
	xor	a3, a3, a4
.endm

/* --------------------------------------- hal_aes_status_t hal_aes_encrypt_block
 *   a0 = const uint8_t in[16]
 *   a1 =       uint8_t out[16]
 * out may alias or overlap in: all 16 input bytes are read in the prologue,
 * before any output byte is written in the epilogue.
 */
	.globl	hal_aes_encrypt_block
	.type	hal_aes_encrypt_block, @function
hal_aes_encrypt_block:
	mv	t5, ra			/* ra becomes the link for sub4      */
	mv	a6, a1			/* out                               */
	mv	a5, a0			/* in                                */
	la	t0, aes_a_sbox
	li	t3, 0x80808080
	li	t4, 0x1b

	/* transpose the input into row words */
	ROWIN	a0, 0
	ROWIN	a1, 1
	ROWIN	a2, 2
	ROWIN	a3, 3

.ifdef AES_A_UNROLL
	/* ---------------- fully unrolled: measurement build only --------- */
	la	t1, aes_a_rk
	lw	a4, 0(t1)
	xor	a0, a0, a4
	lw	a4, 4(t1)
	xor	a1, a1, a4
	lw	a4, 8(t1)
	xor	a2, a2, a4
	lw	a4, 12(t1)
	xor	a3, a3, a4
	.set	rnd, 1
	.rept	9
	SUBROW	a0, 0
	SUBROW	a1, 1
	SUBROW	a2, 2
	SUBROW	a3, 3
	MIXCOLUMNS
	lw	a4, 16*rnd+0(t1)
	xor	a0, a0, a4
	lw	a4, 16*rnd+4(t1)
	xor	a1, a1, a4
	lw	a4, 16*rnd+8(t1)
	xor	a2, a2, a4
	lw	a4, 16*rnd+12(t1)
	xor	a3, a3, a4
	.set	rnd, rnd+1
	.endr
	SUBROW	a0, 0
	SUBROW	a1, 1
	SUBROW	a2, 2
	SUBROW	a3, 3
	lw	a4, 160(t1)
	xor	a0, a0, a4
	lw	a4, 164(t1)
	xor	a1, a1, a4
	lw	a4, 168(t1)
	xor	a2, a2, a4
	lw	a4, 172(t1)
	xor	a3, a3, a4
.else
	/* ---------------- rolled: the shipping shape --------------------- */
	/*
	 * Enter at the AddRoundKey block so round key 0 costs no separate
	 * code: t1 starts one round key low and the block's own `addi` walks
	 * it onto rk[0].  Eleven AddRoundKeys, ten rounds, one copy of each.
	 *
	 * The counter is 10, not 11: the entry jump already performs one
	 * AddRoundKey, and t2 is decremented at the TOP of each pass, so ten
	 * passes leaves t2 == 0 exactly as the last round's AddRoundKey runs.
	 */
	la	t1, aes_a_rk-16
	li	t2, 10
	j	2f
1:	addi	t2, t2, -1
	SUBROW	a0, 0
	SUBROW	a1, 1
	SUBROW	a2, 2
	SUBROW	a3, 3
	beqz	t2, 2f			/* round 10 has no MixColumns        */
	MIXCOLUMNS
2:	addi	t1, t1, 16
	lw	a4, 0(t1)
	xor	a0, a0, a4
	lw	a4, 4(t1)
	xor	a1, a1, a4
	lw	a4, 8(t1)
	xor	a2, a2, a4
	lw	a4, 12(t1)
	xor	a3, a3, a4
	bnez	t2, 1b
.endif

	/* transpose the rows back out */
	mv	a5, a6
	ROWOUT	a0, 0
	ROWOUT	a1, 1
	ROWOUT	a2, 2
	ROWOUT	a3, 3
	li	a0, 0			/* HAL_AES_OK -- see hal_aes.h            */
	jr	t5
	.size	hal_aes_encrypt_block, . - hal_aes_encrypt_block

.ifndef AES_A_INLINE
/* ------------------------------------------------------------------ sub4 --
 * t6 -> a4 : four parallel S-box lookups, a4 = S[b3]<<24 | ... | S[b0].
 * Clobbers a4, a5.  Reads t0 (S-box base).  Does not touch ra.
 *
 * 20 instructions, 50 bytes, 24 cycles.  Called forty times per block, so the
 * jal/ret pair and the two argument moves cost 6 cycles per call, 240 per
 * block -- that is exactly the price of fitting the budget, and it is measured
 * against the inlined build in README.md.
 */
	.type	aes_a_sub4, @function
aes_a_sub4:
	srli	a5, t6, 24
	add	a5, a5, t0
	lbu	a4, 0(a5)
	slli	a5, t6, 8
	srli	a5, a5, 24
	add	a5, a5, t0
	lbu	a5, 0(a5)
	slli	a4, a4, 8
	or	a4, a4, a5
	slli	a5, t6, 16
	srli	a5, a5, 24
	add	a5, a5, t0
	lbu	a5, 0(a5)
	slli	a4, a4, 8
	or	a4, a4, a5
	andi	a5, t6, 255
	add	a5, a5, t0
	lbu	a5, 0(a5)
	slli	a4, a4, 8
	or	a4, a4, a5
	ret
	.size	aes_a_sub4, . - aes_a_sub4
.endif

	.globl	aes_a_code_end
aes_a_code_end:

