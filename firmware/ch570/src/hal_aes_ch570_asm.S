/* ==========================================================================
 * VARIANT F — flash-resident, shaped to the 128-byte ROM loop buffer.
 * 3,960-3,992 cycles/block (the spread is code-layout, not behaviour),
 * measured by firmware/validation on V3C silicon at production CORECFGR 0x2D;
 * fold
 * b106130c on the 512-block differential. (Bench builds of the same kernel
 * measured 3,796/3,797 -- link alignment and harness overhead, not a
 * behaviour difference.) ZERO bytes of code in SRAM, 432 B of data (256 B
 * S-box + 176 B schedule). Leaves the radio .highcode entirely untouched.
 *
 * REQUIRES CORECFGR bit 3 (ROM_LOOP_ACC). With it clear this is still
 * bit-exact but degrades to ~42,000-68,000 cycles/block, which is why the
 * selector #errors rather than build it that way. Production boots 0x2D
 * (bit 3 SET) — see hal_aes_ch570_impl.h and ch570_corecfgr.h.
 *
 * Its 108-byte inner loop body sits inside the measured <=112 B unconditional
 * band. Do not grow it: at 120 B it needs .balign 128 to work at all, and at
 * 128 B it stops being accelerated entirely.
 * ========================================================================== */

/*
 * OpenKeyboard.org OpenDongle
 * AES-128 forward cipher, variant F: FLASH-RESIDENT, LOOP-BUFFER-SIZED.
 *
 * Every other variant of this exercise fights over 956 bytes of SRAM by
 * relocating code into .highcode.  This one puts ZERO code in SRAM.  It runs
 * from flash and instead makes the whole cipher fit the QingKe V3 ROM_LOOP_ACC
 * loop buffer (CORECFGR bit 3), which on this silicon runs a flash-resident
 * loop body of <=112 bytes at ~1.10 cycles/instruction -- inside 7% of SRAM
 * speed -- at any alignment, and <=120 bytes if the loop head is 128-byte
 * aligned.
 *
 * The consequence is that the shape of the cipher is dictated by ONE number:
 * the byte size of the loop body.  So:
 *
 *   - There is exactly ONE loop over the entire cipher.  Not a loop per round
 *     with a round-boundary tail; not a nest.  One label, one backward branch,
 *     40 iterations = 10 rounds x 4 columns, and 87.6% of all dynamic
 *     instructions execute inside it (98.7% inside some <=112-byte loop, once
 *     the 20-byte AddRoundKey prologue and the 12-byte output loop are
 *     counted).  Only 26 instructions per block -- 1.3% -- are straight-line
 *     flash that the buffer can never cover.
 *   - Everything that would normally be round-boundary code -- which buffer is
 *     the source, which is the destination, which round key, and whether this
 *     round skips MixColumns -- is derived branchlessly from the loop counter
 *     inside the body.  A round boundary costs zero instructions.
 *   - ShiftRows costs zero instructions.  The state is held in memory twice
 *     over (a 16-byte state followed by a copy of itself), so the shifted
 *     source index (4c + 5r) mod 16, which never exceeds 27, is reachable as
 *     four CONSTANT offsets 0/5/10/15 from one base register.  That turns the
 *     gather into four 2-byte `xw` c.lbu with no index arithmetic at all.
 *
 * Body size: 108 bytes / 44 instructions.  See README.md.
 *
 * SRAM cost: 256 B S-box + 176 B round-key schedule = 432 B of .data/.bss,
 * plus a 144-byte stack frame.  No .highcode.  Nothing on the radio hot path
 * moves.
 *
 * ISA: rv32imc_zba_zbb_zbc_zbs_xw.  Uses sh1add (Zba), rori and orc.b (Zbb),
 * and the xw compressed byte load/store forms.  No clmul, no Zbk.
 *
 * CORRECTNESS IS INDEPENDENT OF THE LOOP BUFFER.  With CORECFGR bit 3 off
 * (production's 0x25) this code produces identical ciphertext, just ~30x
 * slower.  The bit is a performance dependency, not a functional one.
 */

/*
 * ---------------------------------------------------------------- registers
 *
 *   s0  x8   ps, then pd (pd = ps ^ 32)     xw c.lbu / c.sb / c.sw base
 *   s1  x9   round-key pointer              c.lw base
 *   a0  x10  gathered byte 0 -> column word w
 *   a1  x11  gathered byte 1 -> u -> round-key word
 *   a2  x12  gathered byte 2 -> T
 *   a3  x13  gathered byte 3 -> h
 *   a4  x14  0x1b1b1b1b                     c.and operand, must be x8-x15
 *   a5  x15  MixColumns mask (-1 or 0)      c.and operand, must be x8-x15
 *   t0  x5   S-box base
 *   t1  x6   B, the 64-byte-aligned state buffer pair
 *   t2  x7   caller's `out`
 *   t3  x28  d, the loop counter: -144, -140, ... , +12
 *   t4  x29  scratch
 *   t6  x31  0x80808080
 *
 * Only s0/s1 are callee-saved, so the frame is two words plus the buffer.
 *
 * ------------------------------------------------------------ the counter d
 *
 * d runs -144, -140, ... , +12, step 4, 40 iterations, and encodes the entire
 * round structure:
 *
 *   d & 12         = 4c, the column offset                     (0,4,8,12)
 *   (d & 16) << 1  = source buffer select                      (0 or 32)
 *                    d advances 16 per round, so bit 4 flips every round
 *   d >> 31        = -1 for rounds 1..9, 0 for round 10        (MixColumns on)
 *                    d < 0 for the first 36 iterations = 9 rounds
 *
 * The final state always lands in the buffer at B+32, because the last
 * iteration has d = 12 -> select 0 -> source B+0 -> dest B+32.
 *
 * ------------------------------------------------------------- state layout
 *
 * 64 bytes at B, 64-byte aligned:
 *
 *   B+ 0..15  state A     B+16..31  copy of state A
 *   B+32..47  state B     B+48..63  copy of state B
 *
 * B must be 64-byte aligned so that `xori s0, s0, 32` swaps A<->B exactly:
 * ps = B + sel + 4c with sel in {0,32} and 4c <= 12, so bit 5 is the buffer
 * select and nothing below it can carry into it.
 */

	.option	arch, rv32imc_zba_zbb_zbc_zbs_xw

/* ================================================== hal_aes_encrypt_block */
	.section .text.hal_aes_encrypt_block,"ax",@progbits
	.globl	hal_aes_encrypt_block
	.type	hal_aes_encrypt_block,@function
	.balign	4
hal_aes_encrypt_block:
	addi	sp, sp, -144
	sw	s0, 0(sp)
	sw	s1, 4(sp)

	mv	t2, a1			/* stash `out`; a1 is a loop temp    */
	addi	t1, sp, 71
	andi	t1, t1, -64		/* B = 64-byte-aligned buffer pair    */

	lla	t0, aes_f_sbox
	lla	s1, aes_f_rk

	/*
	 * Prologue loop: initial AddRoundKey, 16 iterations, 20-byte body.
	 * Writes the state AND its duplicate.  Falls out with s1 = rk + 16,
	 * which is exactly the round-1 key the main loop wants.
	 *
	 * "read all 16 input bytes before writing any output byte" is honoured
	 * by construction: `in` is fully consumed here, `out` only at the end.
	 */
	addi	s0, t1, 32		/* round 0 writes state B             */
	addi	a3, a0, 16
.Lark0:
	lbu	a1, 0(a0)
	lbu	a2, 0(s1)
	addi	a0, a0, 1
	addi	s1, s1, 1
	xor	a1, a1, a2
	sb	a1, 0(s0)
	sb	a1, 16(s0)
	addi	s0, s0, 1
	bne	a0, a3, .Lark0

	li	t6, 0x80808080
	li	a4, 0x1b1b1b1b
	li	t3, -144
	li	t5, 12			/* loop bound: run through d = +12       */

	/*
	 * Jump over the alignment padding: the padding must not be executed.
	 * The body is 108 bytes, which the measured table says is accelerated
	 * at ANY alignment (<=112 B), so this .balign is margin, not a
	 * requirement -- it buys the best measured cycles/instruction and room
	 * to grow to 120 B without a re-measurement.
	 */
	j	.Lround
	.balign	128
.Lround:
	/* ---- addressing + MixColumns mask, all from d ------------- 18 B -- */
	andi	t4, t3, 16		/* 4  buffer select, 0 or 16          */
	sh1add	s0, t4, t1		/* 4  ps = B + 0 or 32                */
	andi	t4, t3, 12		/* 4  column offset 4c                */
	add	s0, s0, t4		/* 2  ps = B + sel + 4c               */
	srai	a5, t3, 31		/* 4  -1 for rounds 1..9, else 0      */

	/* ---- SubBytes o ShiftRows: four lookups, no load-use stall  36 B -- */
	lbu	a0, 0(s0)		/* 2  s[0][c]                         */
	lbu	a1, 5(s0)		/* 2  s[1][c+1]                       */
	lbu	a2, 10(s0)		/* 2  s[2][c+2]                       */
	lbu	a3, 15(s0)		/* 2  s[3][c+3]                       */
	add	a0, a0, t0		/* 2                                  */
	add	a1, a1, t0		/* 2                                  */
	add	a2, a2, t0		/* 2                                  */
	add	a3, a3, t0		/* 2                                  */
	lbu	a0, 0(a0)		/* 2                                  */
	lbu	a1, 0(a1)		/* 2                                  */
	lbu	a2, 0(a2)		/* 2                                  */
	lbu	a3, 0(a3)		/* 2                                  */
	slli	a1, a1, 8		/* 2                                  */
	slli	a2, a2, 16		/* 2                                  */
	slli	a3, a3, 24		/* 2                                  */
	or	a0, a0, a1		/* 2                                  */
	or	a2, a2, a3		/* 2                                  */
	or	a0, a0, a2		/* 2  w = column word                 */

	/* ---- MixColumns: w ^ T ^ xtime(u),  u = w ^ ror(w,8) ------ 34 B -- */
	rori	a1, a0, 8		/* 4                                  */
	xor	a1, a1, a0		/* 2  u                               */
	rori	a2, a1, 16		/* 4                                  */
	xor	a2, a2, a1		/* 2  T = a0^a1^a2^a3 in every byte   */
	and	a3, a1, t6		/* 4  h = u & 0x80808080              */
	xor	a1, a1, a3		/* 2  u &= 0x7f7f7f7f                 */
	slli	a1, a1, 1		/* 2  no carry between bytes          */
	orc.b	a3, a3			/* 4  0xff per byte where bit 7 set   */
	and	a3, a3, a4		/* 2  -> 0x1b there                   */
	xor	a1, a1, a3		/* 2  u = xtime(u)                    */
	xor	a1, a1, a2		/* 2  ^ T                             */
	and	a1, a1, a5		/* 2  round 10: drop the whole delta  */
	xor	a0, a0, a1		/* 2                                  */

	/* ---- AddRoundKey ------------------------------------------- 6 B -- */
	lw	a1, 0(s1)		/* 2                                  */
	addi	s1, s1, 4		/* 2                                  */
	xor	a0, a0, a1		/* 2                                  */

	/* ---- store the column and its duplicate into the other buf   8 B -- */
	xori	s0, s0, 32		/* 4  pd = ps ^ 32                    */
	sw	a0, 0(s0)		/* 2                                  */
	sw	a0, 16(s0)		/* 2                                  */

	/* ---- loop -------------------------------------------------- 6 B -- */
	addi	t3, t3, 4		/* 2                                  */
	bge	t5, t3, .Lround		/* 4  t5 = 12; 40 iterations          */
.Lround_end:

	/* Epilogue loop: the result is always in state B. 12-byte body. */
	addi	s0, t1, 32
	addi	a3, s0, 16
	mv	a2, t2
.Lout:
	lbu	a0, 0(s0)
	sb	a0, 0(a2)
	addi	s0, s0, 1
	addi	a2, a2, 1
	bne	s0, a3, .Lout

	lw	s0, 0(sp)
	lw	s1, 4(sp)
	addi	sp, sp, 144
	li	a0, 0			/* HAL_AES_OK -- see hal_aes.h */
	ret
	.size	hal_aes_encrypt_block, .-hal_aes_encrypt_block

